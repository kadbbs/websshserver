"""Make a distributable HTML file with no sibling assets or external requests.

This is a source-maintenance helper. The generated file is ready to use as-is.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
client = ROOT / "client"
html = (client / "index.html").read_text()
css = (client / "style.css").read_text()
html = html.replace('<link rel="stylesheet" href="style.css">', "<style>\n" + css + "</style>")
scripts = []
for name in ("ssh.js", "terminal.js", "app.js"):
    script_tag = re.escape(f'<script src="{name}" defer></script>')
    html = re.sub(rf"(?m)^[ \t]*{script_tag}[ \t]*\n?", "", html)
    source = (client / name).read_text()
    if "</script" in source.lower():
        raise SystemExit(f"{name}: escape closing HTML script tags before bundling")
    scripts.append(f"/* {name} */\n{source}")
html = html.replace("</body>", "<script>\n" + "\n".join(scripts) + "\n</script>\n</body>")
license_text = (ROOT / "LICENSE").read_text().strip()
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/bundle_client.py; edit the source files in client/. -->\n<!--\n" + license_text + "\n-->", 1)
output = client / "ssh-client.html"
output.write_text(html)
print(f"Generated {output.relative_to(ROOT)} ({output.stat().st_size:,} bytes)")
